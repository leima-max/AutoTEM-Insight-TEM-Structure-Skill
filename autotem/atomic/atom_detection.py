from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np
from scipy import ndimage as ndi

from autotem.core.models import ArrayReference, AtomLattice, AtomSite, Measurement

try:
    import tifffile
except ImportError:  # pragma: no cover
    tifffile = None

try:
    import imageio.v3 as iio
except ImportError:  # pragma: no cover
    iio = None


ImageInput = str | Path | np.ndarray


@dataclass
class AtomDetectionResult:
    coordinates: np.ndarray
    intensities: np.ndarray
    overlay_path: str | None
    warnings: list[str]
    method: str
    parameters: dict[str, Any]
    confidence: float
    provenance: dict[str, Any]

    def to_atom_lattice(self, coordinate_unit: str = "pixel") -> AtomLattice:
        """
        Convert detector output to the shared core `AtomLattice` contract.

        Notes
        -----
        Internal detector coordinates are stored as `[y, x]`, while `AtomSite`
        expects `x` and `y` fields explicitly.
        """
        allowed_units = {"pm", "nm", "um", "angstrom", "pixel", "unknown"}
        if coordinate_unit not in allowed_units:
            msg = (
                f"Unsupported coordinate_unit={coordinate_unit!r}. "
                f"Choose one of {sorted(allowed_units)}."
            )
            raise ValueError(msg)

        atoms: list[AtomSite] = []
        for idx, ((y, x), intensity) in enumerate(
            zip(self.coordinates, self.intensities, strict=False)
        ):
            intensity_measurement = Measurement(
                value=float(intensity),
                unit="a.u.",
                method=self.method,
                parameters=dict(self.parameters),
                confidence=self.confidence,
                provenance={
                    "source": "atom_detection.intensity_sample",
                    "index": idx,
                },
                warnings=[],
            )
            atoms.append(
                AtomSite(
                    x=float(x),
                    y=float(y),
                    intensity=intensity_measurement,
                    confidence=self.confidence,
                    warnings=[],
                )
            )

        overlay_ref = None
        if self.overlay_path:
            overlay_ref = ArrayReference(
                shape=tuple(),
                dtype="uint8",
                uri=self.overlay_path,
                inline=None,
                description="Atom-column overlay generated by detect_atoms.",
            )

        provenance = {
            "source": "autotem.atomic.atom_detection.detect_atoms",
            "method": self.method,
            "parameters": dict(self.parameters),
            "detector_provenance": dict(self.provenance),
            "coordinate_convention_input": "yx",
            "coordinate_convention_output": "x,y fields in AtomSite",
        }

        return AtomLattice(
            atoms=atoms,
            lattice_vectors=[],
            zone_axis=None,
            coordinate_unit=coordinate_unit,
            overlay=overlay_ref,
            confidence=self.confidence,
            provenance=provenance,
            warnings=list(self.warnings),
        )


def detect_atoms(
    image: ImageInput,
    mode: str = "auto",
    gaussian_sigma: float | None = None,
    min_distance: int = 4,
    threshold_rel: float = 0.25,
    max_atoms: int = 5000,
    slice_index: int = 0,
    overlay_path: str | Path | None = None,
    return_overlay_array: bool = False,
) -> AtomDetectionResult:
    """
    Baseline atom-column detector (C0): LoG/DoG + local maxima.

    Parameters
    ----------
    image:
        Either a 2D numpy array or a path to image files (dm/dm3/dm4/tif/tiff/...).
    mode:
        "auto", "log", or "dog".
    gaussian_sigma:
        Optional preprocessing gaussian blur sigma. Use None or 0 to disable.
    min_distance:
        Minimum pixel spacing between local maxima.
    threshold_rel:
        Relative threshold against response max for peak picking.
    max_atoms:
        Clip very large detections to guard unstable runs.
    slice_index:
        For stack-like inputs (e.g., multi-frame DM), choose which slice to use.
    overlay_path:
        Optional save path for overlay figure (.png recommended).
    return_overlay_array:
        Keep API-compatible extension hook (not used in this baseline).
    """
    warnings: list[str] = []
    input_array, source_info = _load_image(image, warnings, slice_index=slice_index)
    work = _normalize_image(input_array)

    if gaussian_sigma is not None and gaussian_sigma > 0:
        work = ndi.gaussian_filter(work, sigma=float(gaussian_sigma))

    chosen_mode = _resolve_mode(mode, work, warnings)
    response, scales = _response_map(work, chosen_mode)
    coordinates, intensities = _pick_peaks(
        response=response,
        image=input_array,
        min_distance=min_distance,
        threshold_rel=threshold_rel,
        max_atoms=max_atoms,
        warnings=warnings,
    )

    snr = _estimate_snr(input_array)
    blur_score = float(np.var(ndi.laplace(_normalize_image(input_array))))
    _quality_warnings(
        count=len(coordinates),
        image_shape=input_array.shape,
        snr=snr,
        blur_score=blur_score,
        warnings=warnings,
    )
    confidence = _estimate_confidence(
        snr=snr,
        blur_score=blur_score,
        atom_count=len(coordinates),
        image_shape=input_array.shape,
        warning_count=len(warnings),
    )

    overlay_file = None
    if overlay_path is not None:
        overlay_file = str(Path(overlay_path).resolve())
        _save_overlay(input_array, coordinates, overlay_file)

    if return_overlay_array:
        warnings.append("return_overlay_array is reserved and not implemented in this baseline.")

    return AtomDetectionResult(
        coordinates=coordinates.astype(np.float64, copy=False),
        intensities=intensities.astype(np.float64, copy=False),
        overlay_path=overlay_file,
        warnings=warnings,
        method=f"{chosen_mode.upper()} + local_maxima",
        parameters={
            "mode": chosen_mode,
            "gaussian_sigma": gaussian_sigma,
            "min_distance": int(min_distance),
            "threshold_rel": float(threshold_rel),
            "scales": scales,
            "max_atoms": int(max_atoms),
            "slice_index": int(slice_index),
        },
        confidence=confidence,
        provenance={
            "source": source_info,
            "input_shape": tuple(int(x) for x in input_array.shape),
            "input_dtype": str(input_array.dtype),
            "snr_estimate": snr,
            "blur_score": blur_score,
        },
    )


def _load_image(
    image: ImageInput,
    warnings: list[str],
    slice_index: int = 0,
) -> tuple[np.ndarray, dict[str, Any]]:
    if isinstance(image, np.ndarray):
        arr = np.asarray(image)
        arr = _to_2d(arr, warnings, slice_index=slice_index)
        return arr.astype(np.float64, copy=False), {"type": "ndarray"}

    path = Path(image)
    if not path.exists():
        raise FileNotFoundError(f"Input image not found: {path}")
    suffix = path.suffix.lower()
    source = {"type": "file", "path": str(path.resolve()), "suffix": suffix}

    if suffix in {".dm", ".dm3", ".dm4"}:
        arr = _read_dm(path)
    elif suffix in {".tif", ".tiff"}:
        arr = _read_tiff(path)
    else:
        arr = _read_generic(path)

    arr = _to_2d(arr, warnings, slice_index=slice_index)
    return arr.astype(np.float64, copy=False), source


def _read_dm(path: Path) -> np.ndarray:
    try:
        from ncempy.io import dm as dm_io
    except ImportError as exc:  # pragma: no cover
        raise ImportError(
            "DM support requires ncempy. Install it with `pip install ncempy`."
        ) from exc

    data = dm_io.dmReader(str(path))
    if isinstance(data, dict) and "data" in data:
        return np.asarray(data["data"])
    return np.asarray(data)


def _read_tiff(path: Path) -> np.ndarray:
    if tifffile is not None:
        return np.asarray(tifffile.imread(str(path)))
    if iio is not None:
        return np.asarray(iio.imread(path))
    raise ImportError("TIFF reading requires tifffile or imageio. Please install one of them.")


def _read_generic(path: Path) -> np.ndarray:
    if iio is None:  # pragma: no cover
        raise ImportError(
            "Generic image reading requires imageio. Install with `pip install imageio`."
        )
    return np.asarray(iio.imread(path))


def _to_2d(arr: np.ndarray, warnings: list[str], slice_index: int = 0) -> np.ndarray:
    if arr.ndim == 2:
        return arr
    if arr.ndim < 2:
        raise ValueError(f"Input image must be at least 2D, got shape {arr.shape}.")

    warnings.append(
        f"Input has shape {arr.shape}; using slice_index={slice_index} for 2D detection."
    )
    reduced = np.asarray(arr)
    if reduced.ndim == 3:
        # RGB/RGBA-like
        if reduced.shape[-1] <= 4:
            return np.asarray(reduced[..., 0])
        # stack-like
        if not (0 <= slice_index < reduced.shape[0]):
            raise ValueError(
                "slice_index="
                f"{slice_index} out of range for first dimension size {reduced.shape[0]}."
            )
        return np.asarray(reduced[slice_index, ...])

    while reduced.ndim > 2:
        reduced = reduced[0]
    return np.asarray(reduced)


def _normalize_image(image: np.ndarray) -> np.ndarray:
    image = np.asarray(image, dtype=np.float64)
    if not np.isfinite(image).all():
        finite = np.isfinite(image)
        if not finite.any():
            raise ValueError("Input image contains no finite values.")
        replacement = float(np.nanmedian(image[finite]))
        image = np.where(finite, image, replacement)

    p1, p99 = np.percentile(image, [1.0, 99.0])
    span = max(p99 - p1, 1e-12)
    norm = (image - p1) / span
    return np.clip(norm, 0.0, 1.0)


def _resolve_mode(mode: str, image: np.ndarray, warnings: list[str]) -> str:
    mode = mode.lower()
    if mode not in {"auto", "log", "dog"}:
        raise ValueError("mode must be one of {'auto', 'log', 'dog'}.")
    if mode in {"log", "dog"}:
        return mode

    snr = _estimate_snr(image)
    if snr < 8.0:
        warnings.append("Low SNR estimated; using DoG for more robust baseline response.")
        return "dog"
    return "log"


def _response_map(image: np.ndarray, mode: str) -> tuple[np.ndarray, dict[str, float]]:
    if mode == "log":
        sigma = 1.2
        response = -ndi.gaussian_laplace(image, sigma=sigma)
        return response, {"sigma_log": sigma}

    sigma_small = 0.9
    sigma_large = 1.8
    response = ndi.gaussian_filter(image, sigma=sigma_small) - ndi.gaussian_filter(
        image, sigma=sigma_large
    )
    return response, {"sigma_small": sigma_small, "sigma_large": sigma_large}


def _pick_peaks(
    response: np.ndarray,
    image: np.ndarray,
    min_distance: int,
    threshold_rel: float,
    max_atoms: int,
    warnings: list[str],
) -> tuple[np.ndarray, np.ndarray]:
    if min_distance < 1:
        raise ValueError("min_distance must be >= 1.")
    if not 0.0 < threshold_rel <= 1.0:
        raise ValueError("threshold_rel must be in (0, 1].")

    response_max = float(np.max(response))
    if response_max <= 0.0:
        warnings.append("No atoms detected. Response is non-positive everywhere.")
        return np.empty((0, 2), dtype=np.float64), np.empty((0,), dtype=np.float64)

    threshold = float(response_max * threshold_rel)
    footprint = np.ones((2 * min_distance + 1, 2 * min_distance + 1), dtype=bool)
    maxed = ndi.maximum_filter(response, footprint=footprint, mode="nearest")
    mask = (response == maxed) & (response >= threshold)
    ys, xs = np.where(mask)

    if len(ys) == 0:
        warnings.append("No atoms detected. Consider reducing threshold_rel or min_distance.")
        return np.empty((0, 2), dtype=np.float64), np.empty((0,), dtype=np.float64)

    values = response[ys, xs]
    order = np.argsort(values)[::-1]
    ys = ys[order]
    xs = xs[order]

    if len(ys) > max_atoms:
        warnings.append(f"Detected {len(ys)} peaks; clipping to max_atoms={max_atoms}.")
        ys = ys[:max_atoms]
        xs = xs[:max_atoms]

    coords = np.column_stack((ys, xs))
    intensities = image[ys, xs]
    return coords, intensities


def _estimate_snr(image: np.ndarray) -> float:
    image = np.asarray(image, dtype=np.float64)
    smooth = ndi.gaussian_filter(image, sigma=1.2)
    residual = image - smooth
    noise = float(np.std(residual) + 1e-12)
    signal = float(np.percentile(image, 99.0) - np.percentile(image, 1.0))
    return signal / noise


def _quality_warnings(
    count: int,
    image_shape: tuple[int, int],
    snr: float,
    blur_score: float,
    warnings: list[str],
) -> None:
    pixels = int(image_shape[0] * image_shape[1])
    density = count / max(pixels, 1)
    if snr < 6.0:
        warnings.append(f"Low SNR ({snr:.2f}); atom positions may be unstable.")
    if blur_score < 5e-4:
        warnings.append(f"Strong blur estimated (laplacian variance={blur_score:.3e}).")
    if density > 0.03:
        warnings.append(
            f"Peak density is high ({density:.3f} per pixel); check min_distance or preprocessing."
        )


def _estimate_confidence(
    snr: float,
    blur_score: float,
    atom_count: int,
    image_shape: tuple[int, int],
    warning_count: int,
) -> float:
    pixels = max(int(image_shape[0] * image_shape[1]), 1)
    density = atom_count / pixels
    score = 0.5
    score += min(snr / 25.0, 0.25)
    score += min(blur_score / 0.02, 0.15)
    score += 0.1 if 0.0002 < density < 0.02 else -0.05
    score -= min(warning_count * 0.08, 0.32)
    return float(np.clip(score, 0.0, 1.0))


def _save_overlay(image: np.ndarray, coordinates: np.ndarray, path: str) -> None:
    from matplotlib.figure import Figure

    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)

    fig = Figure(figsize=(6, 6), dpi=180)
    ax = fig.subplots()
    ax.imshow(image, cmap="gray")
    if len(coordinates) > 0:
        ax.scatter(coordinates[:, 1], coordinates[:, 0], s=16, c="r", marker="o", linewidths=0.4)
    ax.set_title(f"Detected atoms: {len(coordinates)}")
    ax.axis("off")
    fig.tight_layout()
    fig.savefig(str(p), bbox_inches="tight")
